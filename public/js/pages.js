  const RENDER = { rules, contacts, privacy, cookies };

  const Screen = {
    mount(root, { route }) {
      this.root = root;
      this.page = RENDER[route.page] ? route.page : 'rules';
      // Вкладку правил можно открыть ссылкой #/rules/small, иначе берём последнюю выбранную.
      const want = /\/rules\/small\b/.test(location.hash) ? 'small' : /\/rules\/full\b/.test(location.hash) ? 'full' : savedTab();
      this.tab = want === 'small' ? 'small' : 'full';
      this.onClick = (e) => {
        const b = e.target.closest('[data-tab]');
        if (!b || b.dataset.tab === this.tab) return;
        this.tab = b.dataset.tab;
        saveTab(this.tab);
        this.render();
      };
      root.addEventListener('click', this.onClick);
      this.render();
    },
    /* Почта и ссылка на Discord приходят с сервера чуть позже: перерисовываем, когда они изменились. */
    update() {
      const sig = JSON.stringify([me().contact, me().community]);
      if (sig !== this.sig) this.render();
    },
    render() {
      this.sig = JSON.stringify([me().contact, me().community]);
      document.title = `${TITLES[this.page]} · Detective Game`;
      this.root.innerHTML = `<article class="doc wrap" data-page="${this.page}">${RENDER[this.page](this.tab)}
<p class="doc-back"><a class="btn" href="#/">На главную</a></p></article>`;
    },
    unmount() {
      if (this.root && this.onClick) this.root.removeEventListener('click', this.onClick);
      document.title = 'Detective Game · Убийца среди вас';
    },
  };

  window.Screens = window.Screens || {};
  window.Screens.page = Screen;
  window.Pages = { TITLES };
